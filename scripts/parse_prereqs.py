"""courses.prereq_raw -> prereq_groups, plus docs/DATA_COVERAGE.md.

Spec: S4 (Section 10). Owner: Aastha. Run: python scripts/parse_prereqs.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

COVERAGE_PATH = ROOT / "docs/DATA_COVERAGE.md"
TOPIC_SECTION = "## Topic labelling method comparison"  # written by scripts/tag_topics.py, preserved here
PROGRAM_SECTION = "## Program requirements (S6)"  # written by scripts/parse_programs.py, preserved here

LABEL_RE = re.compile(r"^\s*Prerequisites?:\s*", re.IGNORECASE)
AND_RE = re.compile(r"\s+and\s+", re.IGNORECASE)
CODE_RE = re.compile(r"([A-Z]{2,5})\s*(\d{3})")
APPROVAL_WORDS = ("approval", "permission", "consent", "concurrent")


def _classify(lower: str) -> str:
    if "classification" in lower:
        return "classification"
    if any(w in lower for w in APPROVAL_WORDS):
        return "approval"
    return "unparsed"


def parse_prereq(text: str) -> list[dict]:
    """Spec 10.1 steps 1-6. Groups are ANDed; alternatives within a group are ORed.

    A sub segment that names courses and also says approval/permission/consent ("MATH 304 or approval of
    instructor") yields the course group plus an approval group, as the 10.4 test table requires.
    """
    body = LABEL_RE.sub("", text or "").strip()
    groups: list[dict] = []
    for segment in body.split(";"):
        for sub in AND_RE.split(segment):
            raw = sub.strip().rstrip(".").strip()
            if not raw:
                continue
            lower = raw.lower()
            codes = list(dict.fromkeys(f"{d} {n}" for d, n in CODE_RE.findall(raw)))
            if codes:
                groups.append({"kind": "course", "alternatives": codes, "raw_text": raw})
                if any(w in lower for w in APPROVAL_WORDS[:3]):
                    groups.append({"kind": "approval", "alternatives": [], "raw_text": raw})
            else:
                groups.append({"kind": _classify(lower), "alternatives": [], "raw_text": raw})
    for i, g in enumerate(groups):
        g["group_index"] = i
    return groups


def load_overrides(path=None) -> dict:
    from backend.app.config import PREREQ_OVERRIDES_PATH

    path = Path(path or PREREQ_OVERRIDES_PATH)
    return json.loads(path.read_text()) if path.exists() else {}


def coverage_report(courses, groups_by_code) -> str:
    def pct(n, total):
        return f"{n} ({100 * n / total:.1f}%)" if total else "0 (0.0%)"

    def block(rows, title):
        n = len(rows)
        has_text = [c for c in rows if c.prereq_raw]
        kinds = {c.code: {g["kind"] for g in groups_by_code.get(c.code, [])} for c in rows}
        course_grp = [c for c in rows if "course" in kinds[c.code]]
        only_cls = [c for c in rows if kinds[c.code] and kinds[c.code] <= {"classification", "approval"}]
        unparsed = [c for c in rows if "unparsed" in kinds[c.code]]
        return "\n".join([
            f"### {title}", "", "```",
            f"Prerequisite text present:          {pct(len(has_text), n)}",
            f"At least one parsed course group:   {pct(len(course_grp), n)}",
            f"Only classification or approval:    {pct(len(only_cls), n)}",
            f"No prerequisite text at all:        {pct(n - len(has_text), n)}",
            f"Contains an unparsed fragment:      {pct(len(unparsed), n)}",
            "```",
        ])

    known = {c.code for c in courses}
    referenced = {a for gs in groups_by_code.values() for g in gs for a in g["alternatives"]}
    missing = sorted(referenced - known)
    rec = [c for c in courses if c.is_recommendable]
    return "\n".join([
        "# Data coverage", "",
        "Generated by `scripts/parse_prereqs.py` (S4) and `scripts/tag_topics.py --compare` (S5). Do not edit by hand.",
        "", "## Prerequisite parsing (S4)", "", "```",
        f"Total courses: {len(courses)}",
        f"Recommendable (graduate CSCE/ECEN): {len(rec)}", "```", "",
        block(rec, "Recommendable courses (the number that goes in the report)"), "",
        block(courses, "All courses"), "",
        "Course codes referenced that are not in the courses table:", "",
        "```", "  " + (", ".join(missing) if missing else "(none)"), "```", "",
    ])


def main():
    from sqlalchemy import delete, select

    from backend.app.db import SessionLocal, init_db
    from backend.app.models import Course, PrereqGroup

    init_db()
    overrides = load_overrides()
    with SessionLocal() as db:
        courses = db.scalars(select(Course).order_by(Course.code)).all()
        db.execute(delete(PrereqGroup))
        groups_by_code = {}
        for c in courses:
            if c.code in overrides:
                groups = [{"kind": g["kind"], "alternatives": g.get("alternatives", []),
                           "raw_text": g.get("raw_text", "override"), "group_index": i}
                          for i, g in enumerate(overrides[c.code])]
            else:
                groups = parse_prereq(c.prereq_raw)
            groups_by_code[c.code] = groups
            db.add_all(PrereqGroup(course_code=c.code, group_index=g["group_index"], kind=g["kind"],
                                   alternatives=json.dumps(g["alternatives"]), raw_text=g["raw_text"])
                       for g in groups)
        db.commit()

    report = coverage_report(courses, groups_by_code)
    old = COVERAGE_PATH.read_text() if COVERAGE_PATH.exists() else ""
    later = [old.index(s) for s in (PROGRAM_SECTION, TOPIC_SECTION) if s in old]
    if later:  # keep the sections parse_programs.py and tag_topics.py wrote
        report += "\n" + old[min(later):]
    COVERAGE_PATH.parent.mkdir(parents=True, exist_ok=True)  # docs/ is not in git; fresh clones lack it
    COVERAGE_PATH.write_text(report)
    print(report)


if __name__ == "__main__":
    main()
