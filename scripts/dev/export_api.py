"""Write docs/API.md from the FastAPI app's OpenAPI schema without starting a server (final spec 13.2).
Regenerate whenever an endpoint changes. Run: python scripts/dev/export_api.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUT = ROOT / "docs/API.md"

# Error bodies the handlers return directly (JSONResponse), which OpenAPI does not see.
ERRORS = {
    ("GET", "/api/profile/{student_id}"): ["404 `{\"error\":\"unknown_student\"}`"],
    ("PUT", "/api/profile/{student_id}"): ["404 `unknown_student`", "422 `{\"error\":\"validation\",\"detail\":[...]}`"],
    ("PATCH", "/api/profile/{student_id}/inferences/{inference_id}"): ["404 `unknown_student`", "404 `{\"error\":\"unknown_inference\"}`"],
    ("POST", "/api/samples/{name}/load"): ["404 `unknown_sample`", "404 `unknown_student`", "422 `validation`"],
    ("POST", "/api/recommend"): ["404 `unknown_student`", "503 `{\"error\":\"index_not_ready\"}`", "422 `validation` (clarification_answer)"],
    ("POST", "/api/chat"): ["404 `unknown_student`",
                            "503 `{\"error\":\"no_api_key\",\"message\":\"Chat is unavailable. No Anthropic API key is configured.\"}` (COURSEMATCH_CHAT=claude only)",
                            "503 `{\"error\":\"llm_unavailable\",\"message\":\"Chat is unavailable right now. Try again.\"}` (COURSEMATCH_CHAT=claude only)"],
    ("POST", "/api/feedback"): ["404 `unknown_student`", "422 `validation`"],
    ("POST", "/api/events"): ["Never fails: always 200 `{\"ok\": true}`"],
}
STUDY_ERRORS = ["422 `{\"error\":\"invalid_code\"}` when the code does not match `^P\\d{3}$`",
                "404 `{\"error\":\"unknown_participant\"}`"]
STUDY_EXTRA = {
    "/api/study/task/start": ["403 `{\"error\":\"no_consent\"}`", "409 `{\"error\":\"out_of_order\"}`"],
    "/api/study/task/submit": ["409 `out_of_order`", "422 `{\"error\":\"invalid_answer\",\"codes\":[...]}`"],
    "/api/study/questionnaire": ["409 `out_of_order`", "422 `validation`"],
    "/api/study/break_done": ["409 `out_of_order`"], "/api/study/final": ["409 `out_of_order`"],
}


def resolve(schema, spec, depth=0):
    if depth > 6 or not isinstance(schema, dict):
        return schema
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        return resolve(spec["components"]["schemas"][name], spec, depth + 1) | {"title": name}
    return {k: ([resolve(x, spec, depth + 1) for x in v] if isinstance(v, list)
                else resolve(v, spec, depth + 1) if isinstance(v, dict) else v) for k, v in schema.items()}


def shape(schema, spec) -> str:
    return json.dumps(resolve(schema, spec), indent=2)


def main():
    import backend.app  # noqa: F401  (OpenMP settings)
    from backend.app.main import app

    spec = app.openapi()
    lines = ["# CourseMatch API", "",
             f"Generated by `scripts/dev/export_api.py` from FastAPI's OpenAPI schema ({spec['info']['title']} "
             f"{spec['info']['version']}). Base URL `http://localhost:8000`. Every error body is "
             "`{\"error\": \"<code>\", ...}`; request validation errors are 422 `{\"error\":\"validation\",\"detail\":[...]}`.", ""]
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            m = method.upper()
            lines += [f"## {m} `{path}`", "", op.get("summary", ""), ""]
            if op.get("description"):
                lines += [op["description"].strip(), ""]
            params = op.get("parameters", [])
            if params:
                lines += ["Parameters:", ""]
                lines += [f"- `{p['name']}` ({p['in']}{', required' if p.get('required') else ''}): "
                          f"{resolve(p.get('schema', {}), spec).get('type', 'any')}" for p in params]
                lines += [""]
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if body:
                lines += ["Request body:", "", "```json", shape(body, spec), "```", ""]
            ok = op.get("responses", {}).get("200", {}).get("content", {}).get("application/json", {}).get("schema")
            lines += ["Response 200:", "", "```json", shape(ok, spec) if ok else "{}", "```", ""]
            errs = list(ERRORS.get((m, path), []))
            if path.startswith("/api/study/") and path != "/api/study/config":
                errs += STUDY_ERRORS + STUDY_EXTRA.get(path, [])
            if errs:
                lines += ["Errors:", "", *[f"- {e}" for e in errs], ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {sum(len(v) for v in spec['paths'].values())} endpoints")


if __name__ == "__main__":
    main()
