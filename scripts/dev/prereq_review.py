"""Write docs/PREREQ_REVIEW.md: every recommendable course with an `unparsed` prerequisite group, or one that
names a course code missing from `courses` (final spec 13.4). The worklist for
data/processed/prereq_overrides.json. Run: python scripts/dev/prereq_review.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUT = ROOT / "docs/PREREQ_REVIEW.md"


def main():
    from sqlalchemy import select

    from backend.app.db import SessionLocal
    from backend.app.models import Course, PrereqGroup
    from backend.app.readiness import load_overrides

    overrides = load_overrides()
    items = []
    with SessionLocal() as db:
        known = set(db.scalars(select(Course.code)))
        for c in db.scalars(select(Course).where(Course.is_recommendable == 1)):
            groups = db.scalars(select(PrereqGroup).where(PrereqGroup.course_code == c.code)
                                .order_by(PrereqGroup.group_index)).all()
            unparsed = [g for g in groups if g.kind == "unparsed"]
            missing = sorted({a for g in groups for a in json.loads(g.alternatives) if a not in known})
            if unparsed or missing:
                items.append((c, groups, unparsed, missing))
    items.sort(key=lambda t: (not t[0].code.startswith("CSCE"), t[0].code))
    lines = ["# Prerequisite review", "",
             "Generated by `scripts/dev/prereq_review.py`. Recommendable courses whose prerequisite text has an "
             "`unparsed` group or names a course that is not in the `courses` table. Fix wrongly parsed courses in "
             "`data/processed/prereq_overrides.json`, then re-run `python scripts/parse_prereqs.py` and "
             "`python scripts/eval_offline.py`.", "",
             f"Courses to review: {len(items)} ({sum(t[0].code.startswith('CSCE') for t in items)} CSCE, "
             f"{sum(not t[0].code.startswith('CSCE') for t in items)} other). Already overridden: "
             f"{', '.join(sorted(k for k in overrides if not k.startswith('_'))) or 'none'}.", ""]
    for c, groups, unparsed, missing in items:
        lines += [f"## {c.code} {c.title}", ""]
        reasons = (["unparsed group"] if unparsed else []) + ([f"names missing course(s): {', '.join(missing)}"] if missing else [])
        lines += [f"- Why listed: {'; '.join(reasons)}", f"- Override present: {'yes' if c.code in overrides else 'no'}",
                  f"- Raw text: {c.prereq_raw or '(empty)'}", "- Parsed groups:"]
        lines += [f"  {g.group_index}. `{g.kind}` {json.loads(g.alternatives)} from \"{g.raw_text}\"" for g in groups]
        lines += [""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(items)} courses to review")


if __name__ == "__main__":
    main()
