"""Regenerate data/fixtures/api_fixtures.json (spec 7.4) from the real pipeline.

Copies data/processed/coursematch.db to a temporary file, points the app at it, and drives the real
endpoints with FastAPI's TestClient (so no fixture student lands in the committed database). Needs the
index (scripts/build_index.py). `chat` comes from the key-free rule parser; `chat_no_key` is the documented
503 body (only returned when COURSEMATCH_CHAT=claude is forced without a key). Run: python -m scripts.dev.make_fixtures
"""
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

_tmp_db = Path(tempfile.mkdtemp()) / "fixtures.db"
shutil.copy(ROOT / "data/processed/coursematch.db", _tmp_db)
os.environ["COURSEMATCH_DB"] = str(_tmp_db)  # must happen before backend.app is imported
os.environ["COURSEMATCH_CHAT"] = "rules"  # deterministic chat fixture, whatever is in .env

from fastapi.testclient import TestClient  # noqa: E402

from backend.app import schemas as S  # noqa: E402
from backend.app.config import FIXTURES_PATH  # noqa: E402
from backend.app.main import app  # noqa: E402

QUERY = "machine learning for images"
SAMPLE = "ml_focused"
SAVE = "CSCE 753"
CLARIFY_SAMPLE, CLARIFY_QUERY = "first_semester", "distributed cloud systems"


def ok(r):
    assert r.status_code == 200, (r.request.url, r.status_code, r.text)
    return r.json()


def main():
    with TestClient(app) as c:
        sid = ok(c.post("/api/session", json={}))["student_id"]
        fx = {
            "_note": (f"Generated by scripts/dev/make_fixtures.py from the real database and index: student loaded "
                      f"with sample '{SAMPLE}', query '{QUERY}', then '{SAVE}' saved; 'chat' from the key-free rule parser; 'chat_no_key' is the "
                      f"documented 503 body. Shapes follow spec Section 5."),
            "health": ok(c.get("/api/health")),
            "session": {"student_id": sid, "condition": "system"},
            "samples": ok(c.get("/api/samples")),
        }
        ok(c.post(f"/api/samples/{SAMPLE}/load", json={"student_id": sid}))
        fx["recommend"] = ok(c.post("/api/recommend", json={"student_id": sid, "query": QUERY}))
        states = {r["readiness"]["state"] for r in fx["recommend"]["results"]}
        assert states == {"ready", "one_course_first", "not_sure"}, f"fixture query is missing a state: {states}"
        fx["feedback"] = ok(c.post("/api/feedback", json={"student_id": sid, "course_code": SAVE, "action": "save"}))
        fx["profile"] = ok(c.get(f"/api/profile/{sid}"))
        fx["autocomplete"] = ok(c.get("/api/courses/autocomplete", params={"q": "csce 6", "limit": 10}))
        fx["chat"] = ok(c.post("/api/chat", json={"student_id": sid, "message": "I care more about systems than theory now"}))
        fx["chat_no_key"] = {"error": "no_api_key", "message": "Chat is unavailable. No Anthropic API key is configured."}
        fx["events"] = ok(c.post("/api/events", json={"student_id": sid, "event": "expand", "condition": "system"}))
        fx["baseline"] = ok(c.get("/api/baseline/search", params={"q": "machine learning", "top_k": 10}))
        # A student whose results split between two topics that never co-occur (spec 20.1), so the interface
        # can show the clarification prompt in fixtures mode.
        other = ok(c.post("/api/session", json={}))["student_id"]
        ok(c.post(f"/api/samples/{CLARIFY_SAMPLE}/load", json={"student_id": other}))
        fx["recommend_clarification"] = ok(c.post("/api/recommend", json={"student_id": other, "query": CLARIFY_QUERY}))
        assert fx["recommend_clarification"]["clarification"], f"'{CLARIFY_QUERY}' no longer triggers a clarification"

    S.HealthResponse.model_validate(fx["health"]); S.SessionResponse.model_validate(fx["session"])
    S.Profile.model_validate(fx["profile"]); S.SamplesResponse.model_validate(fx["samples"])
    S.AutocompleteResponse.model_validate(fx["autocomplete"]); S.RecommendResponse.model_validate(fx["recommend"])
    S.ChatResponse.model_validate(fx["chat"]); S.FeedbackResponse.model_validate(fx["feedback"])
    S.BaselineResponse.model_validate(fx["baseline"]); S.RecommendResponse.model_validate(fx["recommend_clarification"])
    FIXTURES_PATH.write_text(json.dumps(fx, indent=2) + "\n")
    print("wrote data/fixtures/api_fixtures.json:",
          [(r["code"], r["readiness"]["state"], r["score"]) for r in fx["recommend"]["results"]])


if __name__ == "__main__":
    main()
