"""Write docs/PROMPTS.md: every prompt sent to the language model, verbatim, with its settings and the
validation each output must pass (final spec 13.3). Source for Appendix 2 of the final report.
Run: python scripts/dev/export_prompts.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUT = ROOT / "docs/PROMPTS.md"


def main():
    from backend.app import llm
    from backend.app.chat import SYSTEM_PROMPT
    from backend.app.topics import load_taxonomy
    from scripts.tag_topics import LLM_SYSTEM, LLM_USER, MAX_ASSUMES, MAX_COVERS

    taxonomy = load_taxonomy()
    unescape = lambda s: s.replace("{{", "{").replace("}}", "}")  # noqa: E731  (str.format escaping)
    lines = [
        "# Language model prompts", "",
        "Generated by `scripts/dev/export_prompts.py` from the code that sends them. `{taxonomy}` is filled at "
        "run time with the JSON list of the taxonomy below; every other character is sent as shown.", "",
        "## Settings", "",
        "| Setting | Value |", "|---|---|",
        f"| Model | `{llm.DEFAULT_MODEL}` (override with `COURSEMATCH_LLM_MODEL` in the environment or `.env`) |",
        "| Temperature | 0 |",
        "| Max tokens | 300 (chat and topic labelling) |",
        f"| Timeout | {llm.TIMEOUT_S:g} seconds |",
        f"| Retries | {llm.MAX_RETRIES} (Anthropic client `max_retries`) |",
        "| Called from | `backend/app/llm.py` `complete()` only |", "",
        "The model never ranks, never writes an explanation and never states a prerequisite. Ranking is "
        "`backend/app/rerank.py`, explanations are `backend/app/explain.py`, prerequisites are "
        "`backend/app/readiness.py`.", "",
        "## 1. Chat: message to structured action", "",
        "Sent by `backend/app/chat.py` for each chat message in `auto` mode with a valid key, or in `claude` mode. "
        "System prompt:", "", "```", unescape(SYSTEM_PROMPT), "```", "",
        "User turn: the student's message, verbatim.", "",
        "### Validation (`chat.validate`)", "",
        "- The response must parse as one JSON object whose `action` is one of `update_interests`, `new_query`, "
        "`update_profile`, `explain`, `none`.",
        "- `update_interests`: `add` and `remove` are lists, and every entry is an exact taxonomy topic.",
        "- `new_query`: `query` is a non-empty string.",
        "- `update_profile`: `field` is `credits_per_term` with an integer 3 to 15, or `graduation_term` matching "
        "`^\\d{4}(SP|SU|FA)$`. Any other field is rejected.",
        "- `explain`: one `course_code` or a `course_codes` list of 1 to 3. A bare three-digit number is resolved to "
        "a real course code first (recommendable courses, then CSCE, preferred); every code must match "
        "`^[A-Z]{2,5} \\d{3}$` and exist in `courses`.",
        "- Anything that fails is discarded and nothing is written. In `auto` mode the key-free rule parser then "
        "tries the same message (`fallback_reason=\"invalid_output\"`); any API error also falls back to the rule "
        "parser.", "",
        "## 2. Topic labelling (optional, key-gated)", "",
        "Sent by `scripts/tag_topics.py --llm` once per recommendable course; responses are cached in "
        "`data/processed/topic_cache.json` by course code and taxonomy hash. System prompt:", "",
        "```", unescape(LLM_SYSTEM), "```", "", "User turn:", "", "```", LLM_USER, "```", "",
        "`{prereq}` is the catalog prerequisite text, or `none` when it is empty.", "",
        "### Validation (`tag_topics.parse_llm_labels`)", "",
        "- The response must parse as a JSON object (a surrounding code fence is stripped) whose `covers` and "
        "`assumes` are lists.",
        f"- Topics not in the taxonomy are discarded; duplicates are dropped; at most {MAX_COVERS} `covers` and "
        f"{MAX_ASSUMES} `assumes` are kept.",
        "- A course whose response fails to parse, or whose call fails, is skipped and reported; the others continue.",
        "- Rows are stored with `source='llm'`, which `backend/app/topics.py` prefers over keyword and embedding labels.", "",
        f"## Taxonomy ({len(taxonomy)} topics)", "", "```json", json.dumps(taxonomy, indent=2), "```", "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
