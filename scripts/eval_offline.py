"""Offline evaluation: how much personalisation moves the results, and how feasible they are.

Spec: S24 (Section 30). Owner: Shubham. Reads the four sample profiles (as loaded by
scripts/load_samples.py) and data/fixtures/eval_queries.json; writes docs/EVALUATION.md.
Read-only on the database. Run: python scripts/eval_offline.py
"""
import json
import statistics
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

QUERIES_PATH = ROOT / "data/fixtures/eval_queries.json"
OUT = ROOT / "docs/EVALUATION.md"
EMPTY_STUDENT = "s_eval0000"  # never created, so it has no profile: plain retrieval order
PROGRAM_ONLY = "s_evalmscs"   # program MSCS only; exists inside a rolled-back transaction
STATES = ["ready", "one_course_first", "not_sure"]


def spearman(order_a: list[str], order_b: list[str]) -> float:
    """Spearman rho between two orderings of the same items (no ties)."""
    n = len(order_a)
    if n < 2:
        return 1.0
    pos_b = {c: i for i, c in enumerate(order_b)}
    d2 = sum((i - pos_b[c]) ** 2 for i, c in enumerate(order_a))
    return 1 - 6 * d2 / (n * (n * n - 1))


def only_classification_share(db) -> float:
    """Share of recommendable courses whose prerequisite groups are only classification or approval."""
    from sqlalchemy import select

    from backend.app.models import Course, PrereqGroup

    rec = db.scalars(select(Course.code).where(Course.is_recommendable == 1)).all()
    kinds = {c: set() for c in rec}
    for code, kind in db.execute(select(PrereqGroup.course_code, PrereqGroup.kind).where(PrereqGroup.course_code.in_(rec))):
        kinds[code].add(kind)
    return sum(bool(k) and k <= {"classification", "approval"} for k in kinds.values()) / len(rec)


def main():
    from backend.app.config import RETRIEVAL_K, W_DEGREE, W_INTEREST  # sets OpenMP env first
    from backend.app.db import SessionLocal
    from backend.app.models import StudentStated
    from backend.app.rerank import rank
    from backend.app.retrieval import retrieval_service
    from backend.app.usermodel import load_samples_file
    from scripts.load_samples import sample_student_id

    if not retrieval_service.is_ready():
        raise SystemExit("Index missing. Run scripts/build_index.py first.")
    queries = json.loads(QUERIES_PATH.read_text())["queries"]
    profiles = list(load_samples_file())
    rows = []  # one per (profile, query)
    with SessionLocal() as db:
        db.add(StudentStated(student_id=PROGRAM_ONLY, program="MSCS", preferred_days="[]"))
        db.flush()  # visible to rank(); rolled back below, never committed
        for q in queries:
            cands = retrieval_service.search(q, RETRIEVAL_K)
            base = [r["code"] for r in rank(EMPTY_STUDENT, q, cands, db, top_k=len(cands))]
            prog = [r["code"] for r in rank(PROGRAM_ONLY, q, cands, db, top_k=len(cands))]
            for name in profiles:
                ranked = rank(sample_student_id(name), q, cands, db, top_k=len(cands))
                order = [r["code"] for r in ranked]
                top = ranked[:10]
                rows.append({
                    "profile": name, "query": q,
                    "rho": spearman(order, base),
                    "rho_prog": spearman(order, prog),
                    "rho_prog_base": spearman(prog, base),
                    "overlap10": len(set(order[:10]) & set(base[:10])),
                    "feasible10": sum(r["readiness"]["state"] == "ready" for r in top) / len(top),
                    "mix": {s: sum(r["readiness"]["state"] == s for r in top) for s in STATES},
                    "degree_values": {r["features"]["degree_fit"] for r in ranked},
                    "contrib": {
                        "interest_match": statistics.mean(W_INTEREST * r["features"]["interest_match"] for r in top),
                        "degree_fit": statistics.mean(W_DEGREE * r["features"]["degree_fit"] for r in top),
                        "readiness_adjust": statistics.mean(abs(r["features"]["readiness_adjust"]) for r in top),
                    },
                })
        only_cls_share = only_classification_share(db)
        db.rollback()

    by = {p: [r for r in rows if r["profile"] == p] for p in profiles}
    mean = statistics.mean
    rho_all = mean(r["rho"] for r in rows)
    rho_prog_all = mean(r["rho_prog"] for r in rows)
    rho_pb = mean(r["rho_prog_base"] for r in rows[:: len(profiles)])
    lines = [
        "# Offline evaluation", "",
        f"Generated by `scripts/eval_offline.py` on {date.today().isoformat()}. {len(queries)} queries "
        f"(`data/fixtures/eval_queries.json`) × {len(profiles)} sample profiles = {len(rows)} runs. "
        f"Each run ranks the same {RETRIEVAL_K} retrieval candidates twice: with the profile and with an empty "
        "profile (which, by the S11 rule, is plain retrieval order).", "",
        "## 1. Rank displacement (headline)", "",
        "Spearman correlation between the personalised ranking and the empty-profile ranking over all 50 "
        "candidates. 1.0 = personalisation changed nothing; lower = it moved results more. Also the number of "
        "the empty-profile top 10 still in the personalised top 10.", "",
        "| Profile | mean ρ | min ρ | max ρ | mean top-10 overlap (of 10) | mean ρ vs program-only |",
        "|---|---|---|---|---|---|",
        *(f"| {p} | {mean(r['rho'] for r in rs):.3f} | {min(r['rho'] for r in rs):.3f} | {max(r['rho'] for r in rs):.3f} "
          f"| {mean(r['overlap10'] for r in rs):.1f} | {mean(r['rho_prog'] for r in rs):.3f} |" for p, rs in by.items()),
        f"| **all** | **{rho_all:.3f}** | {min(r['rho'] for r in rows):.3f} | {max(r['rho'] for r in rows):.3f} "
        f"| {mean(r['overlap10'] for r in rows):.1f} | {rho_prog_all:.3f} |", "",
        "Control: an MS CS student with no courses and no interests (\"program-only\") against the empty "
        f"profile gives mean ρ **{rho_pb:.3f}**. That is the part of the displacement caused by the program alone "
        "(degree_fit 0.5 for CSCE, 0.0 for ECEN, plus readiness with no completed courses); the last column "
        "isolates what each student's courses and interests add on top of it.", "",
        "Per query (ρ):", "",
        "| Query | " + " | ".join(profiles) + " |", "|---|" + "---|" * len(profiles),
        *(f"| {q} | " + " | ".join(f"{next(r['rho'] for r in rows if r['query'] == q and r['profile'] == p):.3f}"
                                   for p in profiles) + " |" for q in queries), "",
        "## 2. Feasibility at 10", "",
        "Share of the personalised top 10 that is `ready` for the profile.", "",
        "| Profile | mean | min | max |", "|---|---|---|---|",
        *(f"| {p} | {mean(r['feasible10'] for r in rs):.2f} | {min(r['feasible10'] for r in rs):.2f} | "
          f"{max(r['feasible10'] for r in rs):.2f} |" for p, rs in by.items()), "",
        "## 3. State mix in the top 10", "",
        "Mean count per query of each readiness state in the personalised top 10.", "",
        "| Profile | ready | one_course_first | not_sure |", "|---|---|---|---|",
        *(f"| {p} | " + " | ".join(f"{mean(r['mix'][s] for r in rs):.1f}" for s in STATES) + " |" for p, rs in by.items()),
        "",
        "## 4. Feature contribution", "",
        "Mean absolute contribution to the final score over the personalised top 10: "
        "`0.60 × interest_match`, `0.25 × degree_fit`, `|readiness_adjust|`.", "",
        "| Profile | interest_match | degree_fit | readiness_adjust |", "|---|---|---|---|",
        *(f"| {p} | " + " | ".join(f"{mean(r['contrib'][k] for r in rs):.3f}" for k in ("interest_match", "degree_fit", "readiness_adjust"))
          + " |" for p, rs in by.items()), "",
    ]
    feas = {p: mean(r["feasible10"] for r in rs) for p, rs in by.items()}
    prog_rho = {p: mean(r["rho_prog"] for r in rs) for p, rs in by.items()}
    overlap = mean(r["overlap10"] for r in rows)
    not_sure = mean(r["mix"]["not_sure"] for r in rows)
    contrib = {k: mean(r["contrib"][k] for r in rows) for k in ("interest_match", "degree_fit", "readiness_adjust")}
    biggest = max(contrib, key=contrib.get)
    degree_values = sorted({f for r in rows for f in r["degree_values"]})
    size = "a lot" if rho_all < 0.5 else "moderately" if rho_all < 0.8 else "little"
    share_prog = "most" if abs(rho_pb - rho_all) < 0.1 else "part"
    spread = max(prog_rho.values()) - min(prog_rho.values())
    lines += [
        "## Summary", "",
        f"Personalisation moves results {size}: the mean Spearman correlation between the personalised and the "
        f"non-personalised order is {rho_all:.2f}, and {overlap:.1f} of the plain-retrieval top 10 survive into the "
        f"personalised top 10. {share_prog.capitalize()} of that movement comes from the program alone: an MS CS "
        f"student with no courses or interests already gives ρ = {rho_pb:.2f} against plain retrieval, because "
        f"degree fit takes only the values {degree_values} (no MS CS core courses in the catalog), which lifts CSCE "
        f"courses over ECEN courses of similar relevance. Against that program-only profile, each student's courses "
        f"and interests move the order further (mean ρ = {rho_prog_all:.2f}; per profile "
        f"{min(prog_rho.values()):.2f} for {min(prog_rho, key=prog_rho.get)} to {max(prog_rho.values()):.2f} for "
        f"{max(prog_rho, key=prog_rho.get)}, a spread of {spread:.2f}). Feasibility at 10 ranges from "
        f"{min(feas.values()):.2f} ({min(feas, key=feas.get)}) to {max(feas.values()):.2f} "
        f"({max(feas, key=feas.get)}). On average {not_sure:.1f} of each top 10 are `not_sure`; "
        f"{only_cls_share:.0%} of recommendable courses list only classification or approval prerequisites, so "
        f"the readiness rule cannot reason about them. Of the three score components, {biggest} contributes the "
        f"most (mean {contrib[biggest]:.3f}); interest_match {contrib['interest_match']:.3f}, degree_fit "
        f"{contrib['degree_fit']:.3f}, readiness_adjust {contrib['readiness_adjust']:.3f}.", "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)  # docs/ is not in git; fresh clones lack it
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
